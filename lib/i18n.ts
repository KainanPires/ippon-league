// AS FAIXAS
//
// O VALOR gravado em `users.belt` é sempre em português e minúsculas
// ("azul", "preta"). NUNCA muda: é a chave dos rankings por faixa, dos
// percentis mensais e das comparações. Traduzi-lo criaria contas com "Blau" e
// outras com "azul", e nada disso voltaria a bater certo.
//
// O que se traduz é o RÓTULO. Mesmo padrão dos países: o código fica, o texto
// muda. "azul" continua a ser "azul" na base, e o ecrã mostra Blue, Bleue,
// Azul ou Blau.
//
// Ao contrário do ippon ou do waza-ari, "azul" não é um termo técnico japonês —
// é uma cor, e todas as línguas a dizem à sua maneira.
// ---------------------------------------------------------------------------

const FAIXAS_VALIDAS = ["branca", "azul", "amarela", "verde", "roxa", "marrom", "preta"];

/**
 * O nome da faixa na língua pedida. Aceita qualquer valor e cai em "branca" se
 * não reconhecer — a mesma tolerância do normalizarFaixa do lib/faixas.
 *
 * Não importa o lib/faixas de propósito: esse ficheiro é usado no servidor
 * (recálculo mensal das faixas) e este é um módulo de cliente.
 */
export function nomeFaixa(valor: string | null | undefined, lingua: Lingua): string {
  const v = String(valor || "").trim().toLowerCase();
  const chave = FAIXAS_VALIDAS.includes(v) ? v : "branca";
  return traduzir(lingua, `faixa.${chave}`);
}

/** "Faixa Azul", "Blue belt", "Ceinture bleue", "Blau Gürtel". */
export function rotuloFaixa(valor: string | null | undefined, lingua: Lingua): string {
  return traduzir(lingua, "faixa.rotulo", { faixa: nomeFaixa(valor, lingua) });
}

/** Hook para os ecrãs: `const faixaEm = useNomeFaixa(); faixaEm(belt)` */
export function useNomeFaixa(): (valor: string | null | undefined) => string {
  const ctx = useContext(LinguaContexto);
  const lingua = ctx?.lingua ?? "pt";
  return (valor) => nomeFaixa(valor, lingua);
}

/** Hook para o rótulo completo. */
export function useRotuloFaixa(): (valor: string | null | undefined) => string {
  const ctx = useContext(LinguaContexto);
  const lingua = ctx?.lingua ?? "pt";
  return (valor) => rotuloFaixa(valor, lingua);
}

/** Para o seletor de idioma no perfil. */
export function useLingua(): { lingua: Lingua; mudar: (l: Lingua) => void } {
  const ctx = useContext(LinguaContexto);
  if (!ctx) return { lingua: "pt", mudar: () => {} };
  return { lingua: ctx.lingua, mudar: ctx.mudar };
}
